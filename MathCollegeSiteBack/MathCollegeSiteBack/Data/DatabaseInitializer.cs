    public static async Task InitializeAsync(IServiceProvider services)
    {
        await using var scope = services.CreateAsyncScope();
        var db = scope.ServiceProvider.GetRequiredService<AppDbContext>();

        await db.Database.EnsureCreatedAsync();

        foreach (var topicSeed in BuildCurriculum().Concat(BuildExtendedCurriculum()))
        {
            var topic = await db.Topics
                .SingleOrDefaultAsync(x => x.Slug == topicSeed.Slug);

            if (topic is null)
            {
                topic = new CourseTopic
                {
                    Name = topicSeed.Name,
                    Slug = topicSeed.Slug,
                    Description = topicSeed.Description,
                    Order = topicSeed.Order,
                    IsPublished = true
                };

                db.Topics.Add(topic);
                await db.SaveChangesAsync();
            }
            else
            {
                topic.IsPublished = true;

                // Обновляем описание стартовой темы из предыдущей версии.
                if (topic.Slug == "probability-basics"
                    && topic.Description == "Случайные опыты, события и первые расчёты вероятностей.")
                {
                    topic.Description = topicSeed.Description;
                    await db.SaveChangesAsync();
                }
            }

            foreach (var lessonSeed in topicSeed.Lessons)
            {
                await SeedLessonAsync(db, topic, lessonSeed);
            }
        }
    }

    private static async Task SeedLessonAsync(
        AppDbContext db,
        CourseTopic topic,
        LessonSeed seed)
    {
        var lesson = await db.Lessons
            .SingleOrDefaultAsync(x => x.TopicId == topic.Id && x.Order == seed.Order);

        if (lesson is null)
        {
            lesson = new LearningLesson
            {
                TopicId = topic.Id,
                Title = seed.Title,
                Summary = seed.Summary,
                Content = seed.Content,
                Order = seed.Order,
                IsPublished = true
            };

            db.Lessons.Add(lesson);
            await db.SaveChangesAsync();
        }
        else if (lesson.Title == "Случайные события и вероятность")
        {
            // Расширяем короткий демонстрационный урок, который уже был в базе.
            lesson.Title = seed.Title;
            lesson.Summary = seed.Summary;
            lesson.Content = seed.Content;
            lesson.IsPublished = true;
            await db.SaveChangesAsync();
        }
        else if (lesson.Content.Contains("Сначала выпиши известные данные и искомую величину.", StringComparison.Ordinal)
            && lesson.Content.Contains("Умей своими словами объяснить основное понятие", StringComparison.Ordinal))
        {
            // Обновляем только старый автоматически созданный шаблон объяснения.
            // Тексты, которые преподаватель редактировал вручную, остаются нетронутыми.
            lesson.Content = seed.Content;
            await db.SaveChangesAsync();
        }

        var taskSeeds = seed.Tasks.ToList();
        var nextOrder = taskSeeds.Count == 0 ? 1 : taskSeeds.Max(x => x.Order) + 1;
        while (taskSeeds.Count < 10)
        {
            taskSeeds.Add(BuildGeneratedPracticeTask(
                topic.Slug,
                nextOrder,
                topicSeeds: taskSeeds));
            nextOrder++;
        }

        foreach (var taskSeed in taskSeeds)
        {
            var taskExists = await db.LessonTasks.AnyAsync(
                x => x.LessonId == lesson.Id && x.Order == taskSeed.Order);

            if (taskExists)
            {
                continue;
            }

            var task = new LessonTask
            {
                LessonId = lesson.Id,
                Order = taskSeed.Order,
                Type = taskSeed.Type,
                Prompt = taskSeed.Prompt,
                ExplanationTitle = taskSeed.ExplanationTitle,
                Explanation = taskSeed.Explanation,
                Points = 1m,
                CorrectNumber = taskSeed.CorrectNumber,
                NumericTolerance = taskSeed.NumericTolerance,
                Options = taskSeed.Options
                    .Select(option => new TaskOption
                    {
                        Text = option.Text,
                        IsCorrect = option.IsCorrect
                    })
                    .ToList()
            };

            db.LessonTasks.Add(task);
        }

        await db.SaveChangesAsync();
    }


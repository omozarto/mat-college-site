    private static TaskSeed Choice(
        int order,
        string prompt,
        string explanationTitle,
        string explanation,
        params (string Text, bool IsCorrect)[] options)
    {
        return new TaskSeed(
            order,
            "choice",
            prompt,
            explanationTitle,
            explanation,
            null,
            0m,
            options
                .Select(option => new OptionSeed(option.Text, option.IsCorrect))
                .ToArray());
    }

    private static TaskSeed Number(
        int order,
        string prompt,
        string explanationTitle,
        string explanation,
        decimal correctNumber)
    {
        return new TaskSeed(
            order,
            "number",
            prompt,
            explanationTitle,
            explanation,
            correctNumber,
            0m,
            []);
    }

    private sealed record TopicSeed(
        string Name,
        string Slug,
        string Description,
        int Order,
        LessonSeed[] Lessons);

    private sealed record LessonSeed(
        int Order,
        string Title,
        string Summary,
        string Content,
        TaskSeed[] Tasks);

    private sealed record TaskSeed(
        int Order,
        string Type,
        string Prompt,
        string ExplanationTitle,
        string Explanation,
        decimal? CorrectNumber,
        decimal NumericTolerance,
        OptionSeed[] Options);

    private sealed record OptionSeed(string Text, bool IsCorrect);
